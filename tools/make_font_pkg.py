# Builds rtl/font_pkg.vhd from font8x8_basic.h (Daniel Hepper, public domain).
# Codes 0-127: the font; 128-255: the same glyphs in inverse video.
# Bit 7 of each row is the leftmost pixel.
import re, sys
src = open(sys.argv[1]).read()
rows = re.findall(r'\{\s*((?:0x[0-9A-Fa-f]{2},?\s*){8})\}', src)[:128]
assert len(rows) == 128
def rev(b): return int('{:08b}'.format(b)[::-1], 2)
glyphs = [[rev(int(x, 16)) for x in re.findall(r'0x[0-9A-Fa-f]{2}', r)] for r in rows]
glyphs += [[0xFF ^ b for b in g] for g in glyphs]
out = open(sys.argv[2], 'w')
out.write("-- Generated by tools/make_font_pkg.py from font8x8_basic.h\n")
out.write("-- (Daniel Hepper / Marcel Sondaar, public domain). 128-255 = inverse.\n")
out.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage font_pkg is\n")
out.write("  type font_t is array (0 to 2047) of std_logic_vector(7 downto 0);\n")
out.write("  constant FONT_DATA : font_t := (\n")
flat = [b for g in glyphs for b in g]
for i in range(256):
    line = ",".join('x"%02X"' % b for b in flat[i*8:i*8+8])
    out.write("    %s%s  -- $%02X\n" % (line, "" if i == 255 else ",", i))
out.write("  );\nend package;\n")
