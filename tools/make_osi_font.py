#!/usr/bin/env python3
"""
make_osi_font.py - build rtl/font_pkg.vhd for the terminal + OSI mode

  python make_osi_font.py [--mirror] <font_pkg.vhd> <out.vhd> [osi_chargen.bin]

  --mirror   flip each byte of the dump left-to-right, for ROMs that store
             bit 0 as the leftmost pixel (the UK101's AM2716 character ROM does)

The 2K character ROM holds 256 glyphs of 8 rows (bit 7 = leftmost pixel):

  $00-$1F  OSI graphics          (from the OSI character ROM dump)
  $20-$7F  the terminal's letters (taken from the existing font_pkg.vhd,
           5x7 in a 6x8 cell, so terminal mode is unchanged)
  $80-$FF  OSI graphics          (from the OSI character ROM dump)

Terminal mode shows codes $80-$FF as inverse $00-$7F (done in the VHDL), so
it never uses the stored $80-$FF glyphs. OSI mode shows all 256 as stored.

osi_chargen.bin is a 2048-byte dump of an OSI 540 board / Superboard / UK101
character generator ROM, laid out as code*8 + row with bit 7 the leftmost
pixel (or bit 0 leftmost with --mirror). Without it, the graphics
codes get a placeholder box so OSI mode can still be tried.
"""
import re
import sys


def read_pkg(path):
    data = [int(x, 16) for x in re.findall(r'x"([0-9A-Fa-f]{2})"', open(path).read())]
    if len(data) != 2048:
        sys.exit("%s: expected 2048 bytes, found %d" % (path, len(data)))
    return data


def placeholder():
    box = [0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]
    return box * 256


def main():
    mirror = "--mirror" in sys.argv
    if mirror:
        sys.argv.remove("--mirror")
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    term = read_pkg(sys.argv[1])
    if len(sys.argv) == 4:
        osi = list(open(sys.argv[3], 'rb').read())
        if len(osi) != 2048:
            sys.exit("%s: expected 2048 bytes, found %d" % (sys.argv[3], len(osi)))
        if mirror:
            osi = [int("{:08b}".format(b)[::-1], 2) for b in osi]
        src = "OSI character ROM " + sys.argv[3].replace("\\", "/").split("/")[-1] + \
            (" (mirrored)" if mirror else "")
    else:
        osi = placeholder()
        src = "placeholder boxes (no OSI character ROM given)"

    font = []
    for code in range(256):
        g = term if 0x20 <= code <= 0x7F else osi
        font += g[code * 8:code * 8 + 8]

    with open(sys.argv[2], 'w') as out:
        out.write("-- Generated by tools/make_osi_font.py\n")
        out.write("-- $20-$7F: Adafruit-GFX glcdfont.c 5x7 letters in 6x8 cells\n")
        out.write("--          (BSD licence, (c) 2012 Adafruit Industries)\n")
        out.write("-- $00-$1F, $80-$FF: %s\n" % src)
        out.write("-- Bit 7 = leftmost pixel. Terminal inverse video is made in the VDU.\n")
        out.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage font_pkg is\n")
        out.write("  type font_t is array (0 to 2047) of std_logic_vector(7 downto 0);\n")
        out.write("  constant FONT_DATA : font_t := (\n")
        for i in range(256):
            line = ",".join('x"%02X"' % b for b in font[i * 8:i * 8 + 8])
            out.write("    %s%s  -- $%02X\n" % (line, "" if i == 255 else ",", i))
        out.write("  );\nend package;\n")


if __name__ == "__main__":
    main()
