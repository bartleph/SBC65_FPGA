# Builds rtl/font_pkg.vhd (6x8 cells for the 80-column screen) from
# Adafruit-GFX-Library glcdfont.c (5x7 "classic" font, BSD licence,
# Copyright (c) 2012 Adafruit Industries).
#   python make_font6_pkg.py glcdfont.c ../rtl/font_pkg.vhd
# Codes $20-$7E: the font; other codes below $80 blank; $80-$FF: the same
# glyphs in inverse video. Bit 7 of each row is the leftmost of the 6
# pixels (bits 1-0 are not shown).
import re, sys
src = open(sys.argv[1]).read()
body = src[src.index('font[]'):]
vals = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', body)]
glyphs = []
for c in range(128):
    rows = [0] * 8
    if 0x20 <= c <= 0x7E:
        cols = vals[c * 5:c * 5 + 5]
        for r in range(8):
            for k in range(5):
                if (cols[k] >> r) & 1:
                    rows[r] |= 0x80 >> k
    glyphs.append(rows)
glyphs += [[0xFC ^ b for b in g] for g in glyphs]
out = open(sys.argv[2], 'w')
out.write("-- Generated by tools/make_font6_pkg.py from Adafruit-GFX glcdfont.c\n")
out.write("-- (5x7 font, BSD licence, (c) 2012 Adafruit Industries) in 6x8 cells.\n")
out.write("-- Bit 7 = leftmost pixel, 6 pixels used. 128-255 = inverse.\n")
out.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage font_pkg is\n")
out.write("  type font_t is array (0 to 2047) of std_logic_vector(7 downto 0);\n")
out.write("  constant FONT_DATA : font_t := (\n")
flat = [b for g in glyphs for b in g]
for i in range(256):
    line = ",".join('x"%02X"' % b for b in flat[i*8:i*8+8])
    out.write("    %s%s  -- $%02X\n" % (line, "" if i == 255 else ",", i))
out.write("  );\nend package;\n")
