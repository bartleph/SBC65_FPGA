/* ==========================================================================
 * bin2vhd.c - convert a ROM binary into rom_image_pkg.vhd for the SBC65
 *             FPGA build. Builds with Dev-C++ or any C compiler.
 *
 * Usage:  bin2vhd <rom.bin> <rom_image_pkg.vhd> [hex load address]
 *
 *   The FPGA holds three 8K ROM regions:
 *       ROM_A   $A000-$BFFF
 *       ROM_CD  $C000-$DFFF  ($C000-$C0FF is I/O and not used)
 *       ROM_E   $E000-$FFFF
 *   The load address says where the first byte of the .bin belongs.
 *   If it is left off:
 *       a 32K file is taken as $8000-$FFFF  (your full EEPROM image)
 *       anything else is placed so it ends at $FFFF
 *   Bytes not covered by the file are $FF.
 * ========================================================================== */
#include <stdio.h>
#include <stdlib.h>

static unsigned char mem[65536];

static void emit(FILE *out, const char *name, unsigned base, unsigned size)
{
    unsigned i;
    fprintf(out, "  constant %s : rom8k_t := (\n", name);
    for (i = 0; i < size; i++) {
        if (i % 16 == 0) fprintf(out, "    ");
        fprintf(out, "x\"%02X\"%s", mem[base + i], (i == size - 1) ? "" : ",");
        if (i % 16 == 15) fprintf(out, "  -- $%04X\n", base + i - 15);
    }
    fprintf(out, "  );\n");
}

int main(int argc, char *argv[])
{
    FILE *in, *out;
    long len, load;
    unsigned i;

    if (argc < 3) {
        fprintf(stderr, "usage: bin2vhd <rom.bin> <rom_image_pkg.vhd> [hex load address]\n");
        return 1;
    }
    in = fopen(argv[1], "rb");
    if (!in) { perror(argv[1]); return 1; }
    fseek(in, 0, SEEK_END);
    len = ftell(in);
    fseek(in, 0, SEEK_SET);

    if (argc > 3)            load = strtol(argv[3], NULL, 16);
    else if (len == 32768)   load = 0x8000;
    else                     load = 0x10000 - len;
    if (load < 0 || load + len > 0x10000) {
        fprintf(stderr, "file does not fit below $FFFF at $%lX\n", load);
        return 1;
    }

    for (i = 0; i < 65536; i++) mem[i] = 0xFF;
    if (fread(mem + load, 1, (size_t)len, in) != (size_t)len) { perror("read"); return 1; }
    fclose(in);

    out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); return 1; }
    fprintf(out, "-- Generated by bin2vhd from %s (%ld bytes loaded at $%04lX)\n",
            argv[1], len, load);
    fprintf(out, "-- Reset vector = $%02X%02X\n", mem[0xFFFD], mem[0xFFFC]);
    fprintf(out, "library ieee;\nuse ieee.std_logic_1164.all;\n\n");
    fprintf(out, "package rom_image_pkg is\n");
    fprintf(out, "  type rom8k_t is array (0 to 8191) of std_logic_vector(7 downto 0);\n");
    emit(out, "ROM_A", 0xA000, 8192);
    emit(out, "ROM_CD", 0xC000, 8192);
    emit(out, "ROM_E", 0xE000, 8192);
    fprintf(out, "end package;\n");
    fclose(out);

    printf("%s: %ld bytes at $%04lX -> %s, reset vector $%02X%02X\n",
           argv[1], len, load, argv[2], mem[0xFFFD], mem[0xFFFC]);
    return 0;
}
